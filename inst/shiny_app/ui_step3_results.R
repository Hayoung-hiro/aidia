# Step 3: inspect the confirmed method, export, and explore details.
step3_results_ui <- function() {
  help <- .workflow_help
  row <- .workflow_row
  section <- function(number, title, ...) .workflow_section("results", number, title, ...)
  tabItem(tabName = "results",
    div(class = "configure-compact workflow-results",
      div(class = "workflow-heading",
        tags$p(class = "workflow-eyebrow", "STEP 3 OF 3"),
        h2("Review & export"), uiOutput("confirmed_status")),
      conditionalPanel(condition = "output.optimization_complete",
        section("1", "Confirmed method",
          div(class = "workflow-result-status",
            icon("check-circle", class = "text-semantic-success"),
            tags$strong("Optimization Complete"), uiOutput("results_status_text", inline = TRUE)),
          fluidRow(class = "workflow-metrics",
            valueBoxOutput("summary_box_cycle_time", width = 4),
            valueBoxOutput("summary_box_dppp", width = 4),
            valueBoxOutput("summary_box_windows", width = 4)),
          tags$details(class = "config-more workflow-details",
            tags$summary("Method specifications"),
            div(class = "workflow-summary-grid",
            div(class = "workflow-pane",
              .workflow_subheading("Original method", help("Original method", p("The input fixed method and acquisition settings saved with this confirmed result."))),
              uiOutput("before_summary")),
            div(class = "workflow-pane",
              .workflow_subheading("Generated windows", help("Generated windows", p("Window counts, widths, coverage, and sampling verification from the confirmed optimization."))),
              uiOutput("after_summary")),
            div(class = "workflow-pane",
              .workflow_subheading("m/z range", help("m/z range", p("The strategy, overall m/z span, and width statistics of the generated windows across retention-time groups."))),
              uiOutput("mz_range_summary"))))),

        section("2", "Download",
          row("Method file",
            selectInput("export_format", "Export format", choices = c(
              "Thermo Targeted Mass List" = "thermo", "Center Mass List" = "center_mass",
              "m/z Range List" = "mz_range"), selected = "thermo"),
            div(class = "workflow-download-actions",
              downloadButton("download_method", "Download method", class = "btn-success"),
              downloadButton("download_batch_zip", "All formats (ZIP)", class = "btn-default")),
            info = help("Method file format", p("Choose the format accepted by your method software. The table below shows its exact column names and illustrative example rows."),
              p("All formats (ZIP) downloads this confirmed method in all three supported CSV formats."))),
          div(class = "workflow-export-preview", uiOutput("export_format_preview")),
          tags$details(class = "config-more workflow-details",
            tags$summary("Inspect windows"),
            div(class = "workflow-table-scroll", DT::dataTableOutput("window_preview"))),
          row("Thermo charge",
            numericInput("export_charge_state", "Charge state (z)", value = 1, min = 0, max = 100, step = 1),
            info = help("Thermo charge state",
              p("Applies to the Thermo CSV, including the Thermo file in All Formats ZIP. Default: 1. Use 0 to ignore charge where supported."))),
          conditionalPanel(condition = "input.export_format == 'thermo'",
            row("Run start / end",
              checkboxInput("fill_void", "Fill MS2 gaps at run start and end", value = FALSE),
              conditionalPanel(condition = "input.fill_void == true",
                numericInput("acquisition_end_min", "Run end (min)", value = NA, min = 0, step = 1)),
              info = help("Fill MS2 gaps at run start and end",
                p("Fills the periods before the first RT group and after the last RT group with MS2 isolation windows. The first group extends back to 0 min; the last group extends to the run end you enter."),
                p("With this option off, the export keeps the calculated first and last RT boundaries."),
                p("This changes the Thermo CSV acquisition times, while keeping the m/z windows. If run end is left blank, the last RT group end is used.")))),
          tags$details(class = "config-more workflow-details",
            tags$summary("File naming (optional)"),
            row("File labels",
              textInput("sample_name", "Sample / project", value = "", placeholder = "e.g., HeLa_digest"),
              textInput("condition", "Note", value = "", placeholder = "e.g., 60min_gradient"))),
          row("PDF report",
            selectInput("pdf_report_template", "PDF scope", choices = c(
              "Full report" = "full", "Quick summary" = "minimal"), selected = "full"),
            downloadButton("download_pdf", "Download PDF", class = "btn-default"),
            info = help("PDF report scope", p("Full report includes all plots. Quick summary includes the essential plots and takes less time to generate.")))),

        section("3", "Compare with original",
          div(class = "results-comparison-key",
            span(class = "comparison-original", "Original: saved fixed method"),
            span(class = "comparison-designed", "Designed: confirmed windows"),
            help("About this comparison",
              p("Both methods use the same input observations and the final Thermo export RT intervals. Original uses the fixed m/z range and window count saved when this result was confirmed."),
              p("These are design estimates, not measurements from a new acquisition. Draft edits do not change the comparison. Export run start/end choices update the plotted schedule and window loads."))),
          tags$details(class = "config-more workflow-details results-comparison", open = "open",
            tags$summary(span("Selected acquisition regions"),
              textOutput("comparison_coverage", inline = TRUE)),
            .workflow_subheading("Where will the method acquire?",
              help("Selected acquisition regions",
                p("Both panels show the complete input distribution with identical axes and density colors. Green outlines show the selected acquisition regions; input outside those outlines is not covered. Enable individual windows to inspect their placement."),
                p("Coverage counts each input precursor observation once, even when windows overlap. Original is evaluated over the same delivered RT intervals as Designed. Interior gaps are joined at segment midpoints, exactly as in the Thermo method file."))),
            checkboxInput("comparison_show_windows", "Show individual windows", value = FALSE),
            div(class = "workflow-plot-scroll", plotOutput("comparison_selection_plot", height = "390px")),
            p(class = "results-plot-note", textOutput("comparison_schedule_note", inline = TRUE))),
          tags$details(class = "config-more workflow-details results-comparison",
            tags$summary(span("Acquisition trade-offs"), textOutput("comparison_acquisition", inline = TRUE)),
            .workflow_subheading("What changes over the same analysis time?",
              help("Acquisition trade-offs",
                p("Analysis time is the report's last RT apex minus its first RT apex. Estimated cycles = analysis seconds / saved cycle time. MS1 total = cycles x MS1 scans per cycle; MS2 total = cycles x MS2 windows per cycle."),
                p("DPPP uses the same input median FWHM for both methods. These are timing-model estimates, not raw-file scan counts. Values may increase or decrease; the table does not assume an improvement."),
                p("Parallel acquisition is shown as Parallel for MS1: the stored zero marks concurrent acquisition, not zero MS1 scans. Staggered window counts are per cycle, not the sum of both cycles."))),
            p(class = "results-plot-note", textOutput("comparison_duration", inline = TRUE)),
            div(class = "workflow-table-scroll acquisition-tradeoffs", tableOutput("comparison_acquisition_table"))),
          tags$details(class = "config-more workflow-details results-comparison",
            tags$summary(span("Precursor load balance"), textOutput("comparison_load_note", inline = TRUE)),
            .workflow_subheading("How is precursor load distributed across windows?",
              help("Precursor load balance",
                p("Uses the report's Precursor Load Balance comparison: each point is one window's precursor count, the band is the middle 50%, and the line is the median. Empty windows remain visible."),
                p("Both methods are counted on the same final acquisition RT intervals. Whole method pools those per-window counts; it does not sum different RT groups into a single window."),
                p("CV describes variation relative to the mean. Pooled CV also reflects abundance differences between RT groups; a lower CV alone does not establish better acquisition."))),
            selectInput("comparison_load_view", "View", choices = c("All RT groups" = "rt", "Whole method" = "whole"), selected = "rt"),
            div(class = "workflow-plot-scroll", plotOutput("comparison_load_plot", height = "360px")),
            p(class = "results-plot-note", textOutput("comparison_tradeoff", inline = TRUE))),
          tags$details(class = "config-more workflow-details",
            tags$summary("Advanced acquisition diagnostics"),
            .workflow_subheading("Capacity diagnostics",
              help("Acquisition capacity", p("Info indicators show available capacity. Parallel instruments such as Astral commonly have large DPPP and cycle headroom because their window count follows MS1/MS2 synchronization."))),
            uiOutput("capacity_header"),
            div(class = "capacity-plot-scroll", plotOutput("capacity_dashboard", height = "260px", width = "1200px")),
            uiOutput("capacity_bottleneck"))
        )
      ),
      conditionalPanel(condition = "!output.optimization_complete",
        div(class = "workflow-empty", icon("layer-group"),
          span("Confirm your window settings in step 2 to see results."))),
      div(class = "wizard-nav wizard-nav-between",
        actionButton("btn_to_setup_back", "Adjust window settings", class = "btn-default", icon = icon("arrow-left")),
        actionButton("btn_new_analysis", "Start a new analysis", class = "btn-default", icon = icon("redo")))
    )
  )
}
