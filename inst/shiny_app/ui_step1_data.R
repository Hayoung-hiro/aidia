# Step 1: the input report, its acquisition settings, and a sampling check.
step1_data_ui <- function() {
  help <- .workflow_help
  row <- .workflow_row
  section <- function(number, title, ...) .workflow_section("data", number, title, ...)
  upload_status <- function(label) {
    div(class = "workflow-upload-status", role = "status", `aria-live` = "polite",
      span(class = "workflow-upload-icon", `aria-hidden` = "true", "\u25cb"),
      span(class = "workflow-upload-label", label))
  }
  parallel <- "input.instrument == 'astral' || input.instrument == 'astral_zoom'"
  sequential <- "input.instrument == 'qexactive' || input.instrument == 'qexactive_hfx' || input.instrument == 'exploris' || input.instrument == 'eclipse' || input.instrument == 'fusion_lumos'"
  auto_it <- function(ms) {
    div(class = "workflow-it-control",
      tags$label(`for` = paste0(ms, "_it_custom"), "Max IT (ms)"),
      div(class = "workflow-it-values",
      checkboxInput(paste0(ms, "_it_auto"), "Auto", value = TRUE),
      conditionalPanel(condition = paste0("!input.", ms, "_it_auto"),
        numericInput(paste0(ms, "_it_custom"), NULL, value = 50,
          min = 5, max = 500, step = 5)),
      conditionalPanel(condition = paste0("input.", ms, "_it_auto"),
        span(textOutput(paste0(ms, "_it_auto_value"), inline = TRUE), class = "workflow-inline-value"))))
  }

  tabItem(tabName = "data",
    div(class = "configure-compact workflow-data",
      div(class = "workflow-heading",
        tags$p(class = "workflow-eyebrow", "Step 1 / 3"),
        h2("Prepare your data")),

      section("1", "Input files",
        row("Input type",
          selectInput("input_type", NULL, choices = c("DIA-NN ID report" = "diann",
            "alphaextract MS1 features" = "ms1_features"), selected = "diann")),
        div(class = "workflow-file-grid",
          conditionalPanel(condition = "input.input_type == 'diann'",
            class = "workflow-file-field", `data-upload-input` = "parquet_file", `data-upload-state` = "empty",
            row("DIA-NN report",
              fileInput("parquet_file", NULL, accept = ".parquet",
                placeholder = "Choose report.parquet", width = "100%"),
              info = help("DIA-NN report", p("Upload one DIA-NN report containing any number of runs, up to 500 MB. Choose the run and quality settings below, then click Compute."))),
            upload_status("Required \u00b7 Choose a report"),
            div(class = "workflow-file-queue",
              local_input_paths_ui("diann"), uiOutput("diann_upload_queue"))),
          conditionalPanel(condition = "input.input_type == 'ms1_features'",
            class = "workflow-file-field", `data-upload-input` = "ms1_files", `data-upload-state` = "empty",
            row("MS1 feature files",
              fileInput("ms1_files", NULL, accept = ".parquet", multiple = TRUE,
                buttonLabel = "Add files...", placeholder = "Choose features.parquet", width = "100%"),
              info = help("Feature files", p("Add files repeatedly from different folders, or select several at once. Identical files are included only once; different files with the same name are allowed. The combined limit is 500 MB. Protein and peptide identities are unavailable for MS1 features."))),
            upload_status("Required \u00b7 Add feature files"),
            div(class = "workflow-file-queue",
              local_input_paths_ui("ms1"), uiOutput("feature_upload_queue"))),
          div(class = "workflow-file-field", `data-upload-input` = "method_file", `data-upload-state` = "empty",
            row("Method template (optional)",
              fileInput("method_file", NULL, accept = ".meth", placeholder = "Choose a template .meth", width = "100%"),
              info = help("Acquisition method", p("Reads the original acquisition settings and fills in the controls below. The confirmed analysis keeps a copy of this template for native .meth export."),
                p("Native methods require the matching Workstation: Exploris 480 5.1 SP1 or Astral 2.2 SP1 for Astral Zoom MS1 with DIA or tMS2 templates. Output uses Full Scan + scheduled tMS2."),
                p("Default installation folders are detected automatically. If your installation is elsewhere, the error message shows the configuration file and path setting to use."))),
            upload_status("Optional \u00b7 No template loaded"),
            uiOutput("method_import_status"))),
        conditionalPanel(condition = "input.input_type == 'diann'", diann_input_options_ui()),
        conditionalPanel(condition = "input.input_type == 'ms1_features'",
          row("Combine runs",
            selectInput("ms1_aggregation", NULL, choices = c(
              "Consensus when matched; otherwise all detections" = "auto",
              "All detections" = "pooled", "Matched feature consensus" = "consensus"), selected = "auto"),
            conditionalPanel(condition = "input.ms1_aggregation != 'pooled'",
              numericInput("ms1_min_runs", "Min. runs (0 = auto)", value = 0, min = 0, step = 1)),
            info = help("Combine runs",
              p("Use feature tables from the same batch with compatible LC and acquisition conditions. Select runs suitable for your design."),
              p("Joint alphaextract exports provide matched feature groups for consensus. Consensus uses median positions and peak widths, retaining features detected in at least half the selected runs. Independent feature tables are pooled without matching; every detection counts once, so runs with more features contribute more."),
              p("For consensus only: Minimum runs = 0 uses half the selected runs, rounded up. Set 1 to retain features found in any run.")))),
        div(class = "workflow-compute-actions",
          conditionalPanel(condition = "input.input_type == 'diann'", class = "workflow-inline",
            actionButton("compute_diann", "Compute", icon = icon("calculator"), class = "btn-primary"),
            actionButton("clear_diann_files", "Clear list", icon = icon("trash"))),
          conditionalPanel(condition = "input.input_type == 'ms1_features'", class = "workflow-inline",
            actionButton("compute_features", "Compute", icon = icon("calculator"), class = "btn-primary"),
            actionButton("clear_feature_files", "Clear list", icon = icon("trash")))),
        uiOutput("input_scope_summary")),

      section("2", "Input acquisition settings",
        div(class = "workflow-acquisition-grid",
          div(class = "workflow-acquisition-controls",
        row("Instrument",
          selectInput("instrument", "Instrument", choices = c(
            "Thermo Astral Zoom (270 Hz)" = "astral_zoom",
            "Thermo Astral (200 Hz)" = "astral",
            "Thermo Q Exactive (12 Hz)" = "qexactive",
            "Thermo Q Exactive HF-X (40 Hz)" = "qexactive_hfx",
            "Thermo Exploris 480 (40 Hz)" = "exploris",
            "Thermo Eclipse Tribrid (40 Hz)" = "eclipse",
            "Thermo Fusion Lumos (20 Hz)" = "fusion_lumos"), selected = "astral_zoom"),
          info = help("Input acquisition settings", p("Match these settings to the method used to acquire your uploaded report. They define the input cycle time used for comparison with the new method."))),
        row("MS1",
          conditionalPanel(condition = sequential, class = "workflow-scan-controls",
            selectInput("ms1_resolution", "Resolution", choices = c(
              "15,000" = 15000, "30,000" = 30000, "60,000" = 60000,
              "120,000" = 120000, "240,000" = 240000, "480,000" = 480000), selected = 60000)),
          conditionalPanel(condition = parallel,
            selectInput("astral_ms1_resolution", "Resolution (Orbitrap)", choices = c(
              "60,000" = 60000, "120,000" = 120000, "240,000" = 240000,
              "480,000" = 480000), selected = 240000)),
          numericInput("ms1_agc", "AGC (%)", value = 100, min = 1, max = 10000, step = 10),
          auto_it("ms1"),
          info = help("MS1 acquisition settings",
            p("AGC (%) is the normalized AGC target, not the absolute ion count."),
            p("Resolution is the Orbitrap MS1 setting, including for Astral instruments. Higher resolution increases transient duration."),
            p("The timing estimate uses the Orbitrap transient for Auto max IT. Turn Auto off to enter your input method's maximum injection time."))),
        row("MS2",
          conditionalPanel(condition = sequential, class = "workflow-scan-controls",
            selectInput("ms2_resolution", "Resolution", choices = c(
              "7,500" = 7500, "15,000" = 15000, "30,000" = 30000, "45,000" = 45000,
              "60,000" = 60000, "120,000" = 120000, "240,000" = 240000), selected = 15000),
            auto_it("ms2")),
          conditionalPanel(condition = parallel,
            sliderInput("astral_ms2_it", "Injection time (ms)", min = 2, max = 40,
              value = 3, step = 0.1, post = " ms", ticks = FALSE)),
          numericInput("ms2_agc", "AGC (%)", value = 100, min = 1, max = 10000, step = 10),
          info = help("MS2 acquisition settings",
            p("AGC (%) is the normalized AGC target, not the absolute ion count."),
            p("Sequential instruments use the selected MS2 resolution and maximum injection time. Auto max IT matches the transient duration."),
            p("For Astral, use the slider to match MS2 injection time to your input method. Longer injection times change the calculated acquisition speed."))),
        row("Input windows",
          numericInput("current_window_count", "Per cycle", value = 40, min = 10, max = 500, step = 5),
          info = help("Input windows per cycle", p("Enter the number of windows in the method that produced your report. Configure the new window count in step 2."))),
        tags$details(class = "config-more",
          tags$summary("Original m/z range",
            span(class = "workflow-detail-values", .workflow_detail_value("original_mz_min"), "\u2013",
              .workflow_detail_value("original_mz_max", " m/z"))),
          row("Original m/z range",
            numericInput("original_mz_min", "Start", value = 400, min = 1, step = 1),
            numericInput("original_mz_max", "End", value = 1000, min = 1, step = 1),
            info = help("Original method",
              p("Describe the input method's constant m/z range. The reference uses your input window count, with equal widths and no overlap. Defaults to 400-1000 m/z."),
              p("These settings define the comparison reference; they do not restrict optimization."))),
          uiOutput("original_fixed_width"))),
          div(class = "config-preview workflow-acquisition-preview",
            div(class = "config-preview-heading", tags$strong("Acquisition preview"),
              help("Acquisition preview",
                p("Updates from the input acquisition settings. For parallel instruments, the longer of MS1 and the MS2 window sequence determines cycle time. Sequential instruments add their durations."),
                p("After upload, estimated DPPP uses your median peak width and this input cycle time. This is the input method preview; configure the new method in step 2."))),
            uiOutput("acquisition_preview"))
        )),

      section("3", "Peak sampling check",
        conditionalPanel(condition = "!output.data_loaded",
          div(class = "workflow-empty", icon("chart-area"),
            span("Upload data to see peak sampling."))),
        conditionalPanel(condition = "output.data_loaded",
          div(class = "workflow-check-grid",
            div(class = "workflow-pane",
              .workflow_subheading("Peak width distribution",
                help("Peak width (FWHM)", p("The distribution of full widths at half maximum in your report. Peak widths and cycle time determine how many data points sample each peak."))),
              div(class = "workflow-plot-scroll", plotOutput("fwhm_ridgeline", height = "240px"))),
            div(class = "workflow-pane",
              .workflow_subheading("Sampling by cycle time",
                help("Peak sampling (DPPP)", p("DPPP is the number of data points across a peak. Satisfaction is the percentage of peaks meeting your target. The target and required percentage are configured in step 2."))),
              div(class = "workflow-context", "Target DPPP: ", textOutput("current_target_dppp", inline = TRUE)),
              div(class = "workflow-table-scroll", uiOutput("dppp_preview_table")))),
          div(class = "workflow-recommendation", uiOutput("dppp_recommendation")),
          tags$details(class = "config-more workflow-details",
            tags$summary("Timing details"),
            div(class = "workflow-check-grid",
              div(class = "workflow-pane workflow-table-scroll", tableOutput("cycle_time_detail_table")),
              div(class = "workflow-pane",
                .workflow_subheading("Cycle time breakdown"),
                uiOutput("cycle_time_visual"), uiOutput("efficiency_detail"))))
        )),
      uiOutput("prepare_navigation_feedback"),
      div(class = "wizard-nav wizard-nav-right",
        actionButton("btn_to_setup", "Continue to window settings",
          class = "btn-primary", icon = icon("arrow-right")))
    )
  )
}
